export const DICTIONARIES = { en, ru, fr };

// Locale strings arrive as ru_RU.UTF-8, fr-CA, C.UTF-8 and similar; only the
// leading subtag decides, and anything unknown falls back to English.
export function detectLanguage(env = process.env) {
  const raw = env.TAILCHAT_LANG || env.LC_ALL || env.LC_MESSAGES || env.LANG || '';
  const tag = String(raw).toLowerCase().split(/[._-]/)[0];
  return LANGUAGES.includes(tag) ? tag : 'en';
}

export function normaliseLanguage(value) {
  const tag = String(value ?? '').toLowerCase().split(/[._-]/)[0];
  if (!LANGUAGES.includes(tag)) {
    throw new Error(`unknown language: ${value} (expected ${LANGUAGES.join(', ')})`);
  }
  return tag;
}

// On a Mac the shortcut key is ⌘, whatever the terminal delivers to the app
// (blessed only knows `meta`). Every user-facing "Ctrl+" becomes the symbol, so
// one change covers the key list, the command help and the session banners alike.
const MAC = process.platform === 'darwin';

export function createTranslator(lang = 'en') {
  const dictionary = DICTIONARIES[lang] ?? en;
  return function t(key, params) {
    // English is the reference: a key missing from a translation still renders
    // rather than leaving the user with a bare identifier.
    const template = dictionary[key] ?? en[key];
    if (template === undefined) throw new Error(`missing translation key: ${key}`);
    const text = MAC ? template.replace(/Ctrl\+/g, '⌘') : template;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (whole, name) => (
      Object.hasOwn(params, name) ? String(params[name]) : whole
    ));
  };
}
